async(page)=>{
 const base='http://127.0.0.1:8871',project='text-drag-'+Date.now();
 const check=(value,message)=>{if(!value)throw Error(message)};
 const saved=()=>page.waitForFunction(()=>['บันทึกแล้ว','พร้อมแก้ไข'].includes(document.querySelector('#saved').textContent),null,{polling:100});
 const read=async()=>await(await page.request.get(`${base}/api/v1/drafts/${project}`)).json();
 await page.goto(`${base}/?project=${project}`);await page.setViewportSize({width:1440,height:1100});
 await page.locator('[data-step="4"]').click();await saved();
 for(const role of ['speech','emphasis','english'])await page.locator(`[data-role-option=${role}]`).check();await saved();
 const text=page.locator('[data-text-role="speech"]');await text.scrollIntoViewIfNeeded();
 const before=await read(),box=await text.boundingBox();
 const start={x:box.x+box.width/2+10,y:box.y+box.height/2};
 await page.mouse.move(start.x,start.y);await page.mouse.down();
 await page.mouse.move(start.x+30,start.y-40,{steps:8});
 const liveX=await text.evaluate(n=>parseFloat(n.style.left)),liveY=await text.evaluate(n=>parseFloat(n.style.top));
 check(liveX>50 && liveY<69,'drag did not update live X/Y');
 check((await read()).revision===before.revision,'pointer moves created durable revisions');
 await page.mouse.up();await saved();
 const after=await read();
 check(after.revision===before.revision+1,'drop was not one undoable edit');
 check(after.document.text_styles.speech.x===liveX&&after.document.text_styles.speech.y===liveY,'drop did not persist coordinates');
 await page.locator('#undo').click();await saved();check(await text.evaluate(n=>parseFloat(n.style.left))===50,'undo drag failed');
 await page.locator('#redo').click();await saved();check(Number(await text.evaluate(n=>parseFloat(n.style.left)))===liveX,'redo drag failed');
 await text.scrollIntoViewIfNeeded();let b=await text.boundingBox();
 await page.mouse.move(b.x+b.width/2,b.y+b.height/2);await page.mouse.down();await page.mouse.move(b.x+b.width/2-20,b.y+b.height/2+20,{steps:3});
 await page.keyboard.press('Escape');await page.mouse.up();
 check((await read()).revision===after.revision+2,'cancelled drag saved a change');
 check(Number(await text.evaluate(n=>parseFloat(n.style.left)))===liveX,'Escape did not restore position');
 await text.focus();await page.keyboard.press('ArrowLeft');await saved();
 check(Number(await text.evaluate(n=>parseFloat(n.style.left)))===Math.round((liveX-1)*10)/10,'keyboard movement failed');
 await page.reload();await text.waitFor();
 check(Number(await text.evaluate(n=>parseFloat(n.style.left)))===Math.round((liveX-1)*10)/10,'reload lost drop/keyboard position');
 check(await page.locator('#text-x,#text-y').count()===0,'numeric position controls remain');
 await page.setViewportSize({width:1280,height:1000});await text.scrollIntoViewIfNeeded();b=await text.boundingBox();
 await page.mouse.move(b.x+b.width/2,b.y+b.height/2);await page.mouse.down();await page.mouse.move(1,1,{steps:10});await page.mouse.up();await saved();
 const bounds=await page.locator('#textFrame').boundingBox(),placed=await text.boundingBox();
 check(placed.x>=bounds.x-1&&placed.y>=bounds.y-1,'drag moved text outside frame');
 check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile overflow');
 // Snap both axes using the actual pointer, and expose guides only while dragging.
 await text.scrollIntoViewIfNeeded();b=await text.boundingBox();
 const frame=await page.locator('#textFrame').boundingBox();
 await page.mouse.move(b.x+b.width/2,b.y+b.height/2);await page.mouse.down();
 await page.mouse.move(frame.x+frame.width/2+4,frame.y+frame.height/2+4,{steps:10});
 check(await text.evaluate(n=>parseFloat(n.style.left)===50&&parseFloat(n.style.top)===50),'center snap failed');
 check(await page.locator('#alignX').isVisible()&&await page.locator('#alignY').isVisible(),'snap guides missing');
 await page.screenshot({path:'output/text-snap-active.png',fullPage:true});
 await page.mouse.up();await saved();
 check(!await page.locator('#alignX').isVisible()&&!await page.locator('#alignY').isVisible(),'guides stuck after drop');
 check((await read()).document.text_styles.speech.x===50&&(await read()).document.text_styles.speech.y===50,'snap not persisted');
 await text.focus();await page.keyboard.press('ArrowLeft');await saved();
 check(await text.evaluate(n=>parseFloat(n.style.left))===49,'keyboard trapped at snap center');
 await page.evaluate(()=>window.scrollTo(0,0));await page.screenshot({path:'output/text-drag-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1100});await page.screenshot({path:'output/text-drag-desktop.png',fullPage:true});
 console.log(JSON.stringify({project,checks:['mouse drag/live parameters','one revision per drop','undo/redo','Escape cancels','keyboard arrows','reload retains position','pointer outside frame clamped','1280px layout']}));
}
